import sys
import os
import subprocess
import gzip

class FastpFiltering:
    def __init__(self, input_folder, fastp_output_folder, seqtk_output_folder, num_threads, qualified_quality_phred, reads_to_process, seqtk_sample_seed, skip_read_threshold=100):
        self.input_folder = input_folder
        self.fastp_output_folder = fastp_output_folder
        self.seqtk_output_folder = seqtk_output_folder
        self.num_threads = num_threads
        self.qualified_quality_phred = qualified_quality_phred
        self.reads_to_process = reads_to_process
        self.seqtk_sample_seed = seqtk_sample_seed
        self.skip_read_threshold = skip_read_threshold

    def count_reads_in_fastq(self, fastq_file):
        """
        Count the number of reads in a FASTQ file using the zcat and wc commands.
        """
        try:
            # Execute the shell command to count the number of reads
            cmd = f'zcat {fastq_file} | wc -l'
            result = subprocess.run(cmd, shell=True, capture_output=True, text=True, check=True)

            # The number of lines is divided by 4 to get the number of reads
            num_lines = int(result.stdout.strip())
            num_reads = num_lines // 4
            return num_reads
        except subprocess.CalledProcessError as e:
            print(f"Error counting reads in {fastq_file}: {e}", file=sys.stderr)
            return 0

    def filter_reads(self):
        # Create the output folders if they don't exist
        if not os.path.exists(self.fastp_output_folder):
            os.makedirs(self.fastp_output_folder)
        if not os.path.exists(self.seqtk_output_folder):
            os.makedirs(self.seqtk_output_folder)

        # Get a list of all FASTQ files in the input folder
        fastq_files = [f for f in os.listdir(self.input_folder) if f.endswith('.fastq.gz')]

        # Run Fastp and Seqtk for each FASTQ file
        for fastq_file in fastq_files:
            input_path = os.path.join(self.input_folder, fastq_file)
            fastp_output_path = os.path.join(self.fastp_output_folder, fastq_file)
            seqtk_output_path = os.path.join(self.seqtk_output_folder, fastq_file)

            # Run Fastp
            fastp_cmd = f'fastp -i {input_path} -o {fastp_output_path} -A -G --qualified_quality_phred {self.qualified_quality_phred} --thread {self.num_threads}'
            result = subprocess.run(fastp_cmd, shell=True)
            if result.returncode != 0:
                print(f"Error running fastp on {fastq_file}", file=sys.stderr)
                continue

            # Count reads in the fastp output file
            num_reads = self.count_reads_in_fastq(fastp_output_path)
            print(f"File {fastq_file} has {num_reads} reads after fastp processing")  # Debug statement

            # Decide whether to keep the file based on the read count
            if num_reads >= (self.reads_to_process - self.skip_read_threshold):
                # Run Seqtk sample to randomly retrieve reads
                seqtk_cmd = f'seqtk sample -s{self.seqtk_sample_seed} {fastp_output_path} {self.reads_to_process} | gzip > {seqtk_output_path}'
                result = subprocess.run(seqtk_cmd, shell=True)
                if result.returncode != 0:
                    print(f"Error running seqtk on {fastq_file}", file=sys.stderr)
            else:
                print(f"Skipping {fastq_file} due to insufficient reads ({num_reads} reads)")
                
input_folder = sys.argv[1]
fastp_output_folder = sys.argv[2]  # Output folder for results generated by Fastp
seqtk_output_folder = sys.argv[3]  # Output folder for results generated by Seqtk
num_threads = int(sys.argv[4])
qualified_quality_phred = int(sys.argv[5])
reads_to_process = int(sys.argv[6])
seqtk_sample_seed = int(sys.argv[7])  # Seed for Seqtk sample command
skip_read_threshold = int(sys.argv[8])  # Threshold for skipping files with slightly fewer reads

fastp_filtering = FastpFiltering(input_folder, fastp_output_folder, seqtk_output_folder, num_threads, qualified_quality_phred, reads_to_process, seqtk_sample_seed, skip_read_threshold)
fastp_filtering.filter_reads()
